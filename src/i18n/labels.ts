/**
 * Interface language.
 *
 * The prototype is demonstrated in Chinese and submitted in English, so every
 * user-facing string lives here rather than in the components. `Lang` selects the
 * table, and `useT()` returns a `t(key, params)` function bound to the current
 * language choice.
 *
 * Only presentation text is translated. Domain values that are persisted or
 * compared — `TaskStatus`, `TaskKind`, `SourceKind`, `Role`, `Familiarity`,
 * `ProjectKind` — keep their English identifiers as the single source of truth,
 * and are translated at display time via `tStatus`, `tKind` and so on. Changing
 * the interface language therefore cannot alter stored data.
 */

