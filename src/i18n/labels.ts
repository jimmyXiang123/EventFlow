export const DICTS: Record<Lang, Dict> = { zh, en }

/** Translate a key, substituting `{name}` placeholders from `params`. */
export function translate(lang: Lang, key: string, params?: Record<string, string | number>): string {
  const table = DICTS[lang] ?? zh
  const raw = table[key] ?? DICTS.en[key] ?? key
  if (!params) return raw
  return raw.replace(/\{(\w+)\}/g, (_, name) =>
    params[name] === undefined ? `{${name}}` : String(params[name]),
  )
}

/** Locale used for date formatting, so dates match the interface language. */
export function dateLocale(lang: Lang): string {
  return lang === 'zh' ? 'zh-CN' : 'en-GB'
}
